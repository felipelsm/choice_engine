// Tiny 5x7 bitmap font drawn with fill_rect, so any Renderer can show text.
// Uppercase only: lowercase letters are drawn as uppercase.

use crate::render::{Color, Renderer};

pub const GLYPH_W: i32 = 5;
pub const GLYPH_H: i32 = 7;

/// Pixel width of `text` at `scale`.
pub fn text_width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * (GLYPH_W + 1) * scale
}

pub fn draw_text(r: &mut dyn Renderer, text: &str, x: i32, y: i32, scale: i32, color: Color) {
    let mut cx = x;
    for ch in text.chars() {
        let rows = glyph(ch.to_ascii_uppercase());
        for (row, bits) in rows.iter().enumerate() {
            for col in 0..GLYPH_W {
                if bits & (1 << (GLYPH_W - 1 - col)) != 0 {
                    r.fill_rect(cx + col * scale, y + row as i32 * scale, scale, scale, color);
                }
            }
        }
        cx += (GLYPH_W + 1) * scale;
    }
}

